#!/usr/bin/env bash
# Smoke test for Python course demos and unit tests.
# Usage: scripts/smoke.sh [all|day1|day2]
set -u
cd "$(dirname "$0")/.."

MODE="${1:-all}"
fail=0

run_check() {
  local label="$1"
  shift
  if out=$("$@" 2>&1); then
    echo "PASS  $label"
  else
    echo "FAIL  $label"
    echo "$out" | sed 's/^/      /'
    fail=1
  fi
}

if [ "$MODE" = "all" ] || [ "$MODE" = "day1" ]; then
  run_check "Day 1 Beat 1.1 variables"    python3 demos/day1/beat_1_1_variables.py
  run_check "Day 1 Beat 1.2 data types"   python3 demos/day1/beat_1_2_data_types.py
  run_check "Day 1 Beat 1.3 input+cast"   bash -c 'printf "Summarize AI notes\n200\n0.4\n" | python3 demos/day1/beat_1_3_input_casting.py'
  run_check "Day 1 Beat 1.4 loops"        python3 demos/day1/beat_1_4_loops.py
  run_check "Day 1 Beat 1.5 revision"     bash -c 'printf "Translate text\n2\n" | python3 demos/day1/beat_1_5_revision.py'
fi

if [ "$MODE" = "all" ] || [ "$MODE" = "day2" ]; then
  run_check "Day 2 Beat 2.1 functions"       python3 demos/day2/beat_2_1_functions.py
  run_check "Day 2 Beat 2.2 containers"      python3 demos/day2/beat_2_2_containers.py
  run_check "Day 2 Beat 2.3 OOP class/obj"   python3 demos/day2/beat_2_3_oop_class_object.py
  run_check "Day 2 Beat 2.4 OOP __init__"    python3 demos/day2/beat_2_4_oop_constructor.py
  run_check "Day 2 Beat 2.5 OOP self"        python3 demos/day2/beat_2_5_oop_self.py
  run_check "Day 2 Beat 2.6 OOP attr/method" python3 demos/day2/beat_2_6_oop_attributes_methods.py
  run_check "Day 2 Beat 2.7 OOP inheritance" python3 demos/day2/beat_2_7_oop_inheritance.py
  run_check "Day 2 Beat 2.8 comp+Big-O"      python3 demos/day2/beat_2_3_comprehensions_bigo.py
  run_check "Day 2 Beat 2.9 file I/O"        python3 demos/day2/beat_2_4_file_io.py
fi

if [ "$MODE" = "all" ]; then
  run_check "Course verification tests" python3 -m unittest discover -s exercises/tests -v
elif [ "$MODE" = "day1" ]; then
  run_check "Day 1 verification tests" python3 -m unittest exercises.tests.test_demos.TestDay1Demos -v
elif [ "$MODE" = "day2" ]; then
  run_check "Day 2 verification tests" python3 -m unittest exercises.tests.test_demos.TestDay2Demos -v
fi

# Clean up files generated by Beat 2.4 demo during smoke test
rm -f demos/day2/data/run_log.txt demos/day2/data/updated_config.json

echo
if [ $fail -eq 0 ]; then
  echo "ALL CHECKS PASSED"
  exit 0
else
  echo "SOME CHECKS FAILED"
  exit 1
fi
